#!/usr/bin/env node
/**
 * Keyword taxonomy source of truth: taxonomy/keyword-taxonomy.csv
 * (or the published Google Sheet tab — set TAXONOMY_CSV_URL to its
 * `export?format=csv` URL, or pass --url <url>).
 *
 * Generates src/lib/keywordTaxonomy.generated.ts — alias map, display names,
 * facet assignment, and the visible set. Run before tsc; data:lint asserts
 * the committed file is in sync (regenerate to tmp and diff).
 *
 * Usage: node scripts/keyword-taxonomy.mjs [--check] [--out <path>] [--url <csv-url>]
 *   --check  exit 1 when the committed file differs (used by data:lint)
 *   With no URL, reads the committed CSV (what CI and data:lint use).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const TAXONOMY_CSV = join(root, 'taxonomy', 'keyword-taxonomy.csv')
const GENERATED_TS = join(root, 'src', 'lib', 'keywordTaxonomy.generated.ts')

const REQUIRED_COLUMNS = ['Term', 'Aliases', 'Facet', 'Status', 'Comment']
const VALID_STATUS = new Set(['active', 'review', 'pending', 'zero-hit'])
const RENDERED_STATUS = new Set(['active', 'review'])

function parseCsv(text) {
  const rows = []
  let row = []
  let field = ''
  let inQuotes = false
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i]
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i += 1 }
        else inQuotes = false
      } else field += c
    } else if (c === '"') inQuotes = true
    else if (c === ',') { row.push(field); field = '' }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = '' }
    else if (c !== '\r') field += c
  }
  if (field !== '' || row.length > 0) { row.push(field); rows.push(row) }
  const header = (rows.shift() ?? []).map((h) => h.trim())
  return { header, rows }
}

/** Must match the cleaning in canonicalKeywordDisplay (parseTags.ts). */
function normalizeKey(raw) {
  return raw
    .replace(/ /g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[./:;]+$/g, '')
    .trim()
    .toLowerCase()
}

function loadTaxonomy(csvText, sourceLabel) {
  const { header, rows } = parseCsv(csvText)
  for (const col of REQUIRED_COLUMNS) {
    if (!header.includes(col)) throw new Error(`taxonomy CSV (${sourceLabel}) missing column ${col}`)
  }
  const idx = Object.fromEntries(header.map((h, i) => [h, i]))
  const terms = []
  const seenTerms = new Map()
  const aliasOwner = new Map()
  const errors = []
  rows.forEach((r, n) => {
    if (r.every((cell) => cell.trim() === '')) return
    const line = n + 2
    const term = (r[idx.Term] ?? '').trim()
    const facet = (r[idx.Facet] ?? '').trim()
    const status = (r[idx.Status] ?? '').trim()
    const comment = (r[idx.Comment] ?? '').trim()
    const aliases = (r[idx.Aliases] ?? '')
      .split(';')
      .map((a) => a.trim())
      .filter(Boolean)
    if (!term) { errors.push(`line ${line}: empty Term`); return }
    if (!VALID_STATUS.has(status)) { errors.push(`line ${line} (${term}): bad Status ${JSON.stringify(status)}`); return }
    const key = normalizeKey(term)
    if (!key) { errors.push(`line ${line}: Term normalizes to empty`); return }
    if (seenTerms.has(key)) { errors.push(`line ${line} (${term}): duplicate of line ${seenTerms.get(key)}`); return }
    seenTerms.set(key, line)
    for (const a of aliases) {
      const ak = normalizeKey(a)
      if (!ak || ak === key) continue
      if (aliasOwner.has(ak) && aliasOwner.get(ak) !== key) {
        errors.push(`line ${line} (${term}): alias ${JSON.stringify(a)} already maps to another term`)
        continue
      }
      aliasOwner.set(ak, key)
    }
    terms.push({ term, key, aliases, facet, status, comment })
  })
  return { terms, aliasOwner, errors }
}

function emit(terms, aliasOwner) {
  const aliasToCanon = {}
  const display = {}
  const facet = {}
  const status = {}
  const variants = {}
  for (const t of terms) {
    display[t.key] = t.term
    status[t.key] = t.status
    if (t.facet) facet[t.key] = t.facet
    aliasToCanon[t.key] = t.key
    variants[t.key] = []
  }
  for (const [ak, canon] of [...aliasOwner.entries()].sort()) {
    aliasToCanon[ak] = canon
    const raw = terms.find((t) => t.key === canon)?.aliases.find((a) => normalizeKey(a) === ak)
    variants[canon].push(raw ?? ak)
  }
  const visible = terms
    .filter((t) => RENDERED_STATUS.has(t.status))
    .map((t) => t.key)
    .sort()
  const districts = terms
    .filter((t) => t.facet === 'Districts' && (t.status === 'active' || t.status === 'zero-hit'))
    .map((t) => t.term)
    .sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }))
  const str = (v) => JSON.stringify(v)
  const mapLines = (obj) =>
    Object.entries(obj)
      .sort(([a], [b]) => (a < b ? -1 : 1))
      .map(([k, v]) => `  ${str(k)}: ${str(v)},`)
      .join('\n')
  return `// AUTO-GENERATED by scripts/keyword-taxonomy.mjs — do not edit.
// Source of truth: taxonomy/keyword-taxonomy.csv (or TAXONOMY_CSV_URL when set).
// Statuses: active/review render; pending/zero-hit are stored only.

export const KEYWORD_ALIAS_TO_CANONICAL: Record<string, string> = {
${mapLines(aliasToCanon)}
};

export const KEYWORD_DISPLAY: Record<string, string> = {
${mapLines(display)}
};

export const KEYWORD_FACET: Record<string, string> = {
${mapLines(facet)}
};

export const KEYWORD_STATUS: Record<string, string> = {
${mapLines(status)}
};

/** Canonical keys with Status active or review — the only keywords the UI shows. */
export const VISIBLE_KEYWORD_CANONICALS: string[] = [
${visible.map((k) => `  ${str(k)},`).join('\n')}
];

/** Raw alias variants per canonical (for full-text search recall). */
export const KEYWORD_VARIANTS: Record<string, string[]> = {
${Object.entries(variants)
  .filter(([, v]) => v.length > 0)
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(([k, v]) => `  ${str(k)}: [${v.map(str).join(', ')}],`)
  .join('\n')}
};

/** Canonical district names from the taxonomy (Facets Districts, active/zero-hit). */
export const TAXONOMY_DISTRICTS: string[] = [
${districts.map((d) => `  ${str(d)},`).join('\n')}
];
`;
}

const args = process.argv.slice(2)
const check = args.includes('--check')
const outIdx = args.indexOf('--out')
const outPath = outIdx >= 0 ? args[outIdx + 1] : GENERATED_TS
const urlIdx = args.indexOf('--url')
const sourceUrl = urlIdx >= 0 ? args[urlIdx + 1] : process.env.TAXONOMY_CSV_URL || null

async function loadSource() {
  if (!sourceUrl) return { text: readFileSync(TAXONOMY_CSV, 'utf8'), label: TAXONOMY_CSV }
  const response = await fetch(sourceUrl)
  if (!response.ok) {
    throw new Error(`taxonomy CSV fetch failed (${response.status} ${response.statusText}) — ${sourceUrl}`)
  }
  return { text: await response.text(), label: sourceUrl }
}

const { text: csvText, label: sourceLabel } = await loadSource()
const { terms, aliasOwner, errors } = loadTaxonomy(csvText, sourceLabel)
if (errors.length > 0) {
  console.error(`taxonomy errors (${sourceLabel}):`)
  for (const e of errors) console.error(` - ${e}`)
  process.exit(1)
}
const emitted = emit(terms, aliasOwner)

if (check) {
  // The sync check always compares the committed CSV (URL sources are for
  // explicit regeneration, not for the committed-module assertion).
  const { text: localText, label: localLabel } = { text: readFileSync(TAXONOMY_CSV, 'utf8'), label: TAXONOMY_CSV }
  const local = loadTaxonomy(localText, localLabel)
  if (local.errors.length > 0) {
    console.error(`taxonomy errors (${localLabel}):`)
    for (const e of local.errors) console.error(` - ${e}`)
    process.exit(1)
  }
  const committed = readFileSync(GENERATED_TS, 'utf8')
  if (committed !== emit(local.terms, local.aliasOwner)) {
    console.error('keywordTaxonomy.generated.ts is out of sync with taxonomy/keyword-taxonomy.csv — run node scripts/keyword-taxonomy.mjs')
    process.exit(1)
  }
  console.log(`taxonomy sync OK: ${local.terms.length} terms, ${local.aliasOwner.size} aliases, ${local.terms.filter((t) => RENDERED_STATUS.has(t.status)).length} visible`)
} else {
  const tmpOut = outPath === GENERATED_TS ? null : outPath
  if (tmpOut) mkdirSync(dirname(tmpOut), { recursive: true })
  writeFileSync(tmpOut ?? GENERATED_TS, emitted)
  console.log(`taxonomy: ${terms.length} terms (${sourceLabel}) → ${tmpOut ?? GENERATED_TS}`)
}
